import { randomUUID } from "node:crypto";
import { describe, expect, it, vi } from "vitest";
import express from "express";
import request from "supertest";
import { assertFreshLocalTestDatabaseEnvironment } from "../../../../scripts/fresh-test-database.mjs";
const state = vi.hoisted(() => ({ session: null as any }));
vi.mock("../lib/session", () => ({ getSessionFromRequest: () => state.session, requireSession: (_req: any, _res: any, next: any) => next() }));
const isolated = process.env.VNDRLY_TEST_DB_MODE === "fresh-local" && process.env.VNDRLY_ISOLATED_TEST_DB === "1";
describe.skipIf(!isolated)("ticket journeys saved records", () => {
  it("isolates companies and reports partial/full invoice payment and actual history", async () => {
    assertFreshLocalTestDatabaseEnvironment(process.env);
    const s = await import("@workspace/db");
    const { eq } = await import("drizzle-orm");
    const { dashboardTicketJourneysRouter } = await import("./dashboard-ticket-journeys");
    const app = express().use(dashboardTicketJourneysRouter);
    const marker = randomUUID();
    const [vendor] = await s.db.insert(s.vendorsTable).values({ name: `Synthetic journey ${marker}`, contactName: "Synthetic", contactEmail: `${marker}@example.invalid` }).returning();
    const [partner] = await s.db.insert(s.partnersTable).values({ name: `Synthetic partner ${marker}`, contactName: "Synthetic", contactEmail: `partner-${marker}@example.invalid` }).returning();
    const [workType] = await s.db.insert(s.workTypesTable).values({ name: `Journey ${marker}`, category: "operations" }).returning();
    const [site] = await s.db.insert(s.siteLocationsTable).values({ partnerId: partner.id, name: "Synthetic journey site", address: "Synthetic", latitude: 30, longitude: -97, state: "TX", siteCode: `J-${marker.slice(0,20)}` }).returning();
    const now = new Date();
    const [ticket] = await s.db.insert(s.ticketsTable).values({ vendorId: vendor.id, siteLocationId: site.id, workTypeId: workType.id, status: "approved", approvedAt: now, lifecycleState: "off_site" }).returning();
    const [invoice] = await s.db.insert(s.invoicesTable).values({ invoiceNumber: `J-${marker}`, vendorId: vendor.id, partnerId: partner.id, cadence: "weekly", status: "open", periodStart: now, periodEnd: now, total: "100", paidAmount: "25" }).returning();
    await s.db.insert(s.invoiceTicketLinksTable).values({ invoiceId: invoice.id, ticketId: ticket.id, approvedAt: now });
    await s.db.insert(s.invoicePaymentsTable).values({ invoiceId: invoice.id, method: "ach", amount: "25", paidAt: now, referenceNumber: "synthetic-only" });
    await s.db.insert(s.ticketStatusHistoryTable).values({ ticketId: ticket.id, fromStatus: "submitted", toStatus: "approved", reason: "Synthetic approval" });
    state.session = { role: "vendor", vendorId: vendor.id, userId: 1 };
    let list = await request(app).get("/dashboard/ticket-journeys");
    expect(list.status).toBe(200);
    expect(list.body.tickets).toHaveLength(1);
    expect(list.body.tickets[0]).toMatchObject({ id: ticket.id, paid: false, paidAmount: "25.00", balanceDue: "75.00" });
    const detail = await request(app).get(`/dashboard/ticket-journeys/${ticket.id}`);
    expect(detail.status).toBe(200);
    expect(detail.body.history[0].reason).toBe("Synthetic approval");
    expect(detail.body.invoices[0].payments[0].reference).toBe("synthetic-only");
    await s.db.update(s.invoicesTable).set({ status: "paid", paidAmount: "100", paidAt: now }).where(eq(s.invoicesTable.id, invoice.id));
    list = await request(app).get("/dashboard/ticket-journeys");
    expect(list.body.tickets[0]).toMatchObject({ paid: true, balanceDue: "0.00", finishedAt: now.toISOString() });
    state.session.vendorId = -1;
    expect((await request(app).get("/dashboard/ticket-journeys")).body.tickets).toEqual([]);
    expect((await request(app).get(`/dashboard/ticket-journeys/${ticket.id}`)).status).toBe(404);
  });
});
