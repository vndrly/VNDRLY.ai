import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {createRequire} from 'node:module';
const {chromium}=createRequire(new URL('../lib/e2e/package.json',import.meta.url))('@playwright/test');
const expected=process.env.RELEASE_SHA,origin='https://vndrly.ai',output=process.env.PROOF_DIR;
assert.match(expected,/^[a-f0-9]{40}$/);mkdirSync(output,{recursive:true});
const hash=value=>createHash('sha256').update(value).digest('hex');
const htmlResponse=await fetch(origin+'/?release='+expected);
assert.equal(htmlResponse.status,200);
const html=Buffer.from(await htmlResponse.arrayBuffer());
assert.equal(hash(html),hash(readFileSync(path.join(process.env.EXPECTED_WEB_DIR,'index.html'))),'Public index differs from the published release artifact');
const src=html.toString().match(/<script[^>]*src="([^"]+\.js)"/)?.[1];assert.ok(src);
const bundleUrl=new URL(src,origin),bundlePath=path.resolve(process.env.EXPECTED_WEB_DIR,'.'+bundleUrl.pathname);
assert.ok(bundlePath.startsWith(path.resolve(process.env.EXPECTED_WEB_DIR)+path.sep));
const bundleResponse=await fetch(bundleUrl);assert.equal(bundleResponse.status,200);
const bundle=Buffer.from(await bundleResponse.arrayBuffer());
assert.equal(hash(bundle),hash(readFileSync(bundlePath)),'Public bundle differs from the release artifact');
const healthResponse=await fetch(origin+'/api/healthz?release='+expected+'&checked='+Date.now());
assert.equal(healthResponse.status,200);const health=await healthResponse.json();assert.equal(health.status,'ok');
const username='admin@vndrly.com',password=readFileSync('docs/canonical-credentials.md','utf8').split('\n').find(line=>line.startsWith('|')&&line.includes(username))?.split('|')[2]?.match(/`([^`]+)`/)?.[1];assert.ok(password);
const browser=await chromium.launch({headless:true});
try{
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 const login=await context.request.post(origin+'/api/auth/login',{data:{username,password}});
 assert.equal(login.status(),200,'Canonical admin login failed');
 const holdsResponse=await context.request.get(origin+'/api/notifications/company-holds');
 assert.equal(holdsResponse.status(),200);
 const holds=await holdsResponse.json(),midcon=holds.holds.find(h=>h.vendorId===1054);
 assert.ok(midcon);assert.equal(midcon.allRecipientsPaused,true);assert.equal(midcon.automaticResume,false);assert.equal(midcon.expiresAt,null);
 assert.deepEqual([...midcon.channels].sort(),['email','in_app','push','sms']);
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/**',route=>['GET','HEAD','OPTIONS'].includes(route.request().method())?route.continue():route.fulfill({json:{}}));
 await page.goto(origin+'/gate/profile',{waitUntil:'domcontentloaded',timeout:60000});
 await page.getByTestId('gate-profile').waitFor({state:'visible',timeout:30000});
 await page.getByTestId('profile-user-info').waitFor({state:'visible',timeout:30000});
 assert.deepEqual(errors,[],'Profile page raised a JavaScript error');
 await page.screenshot({path:path.join(output,'public-gate-profile.png'),fullPage:true});
 const proof={releaseCommit:expected,checkedAt:new Date().toISOString(),web:{indexSha256:hash(html),bundleSha256:hash(bundle),bundleUrl:bundleUrl.href,artifactMatch:true,renderedPath:'/gate/profile',pageErrors:errors},api:{health,companyHold:midcon},scope:'Real public responses and canonical administrator session; page background writes intercepted; no staff records or preferences changed'};
 writeFileSync(path.join(output,'public-release-proof.json'),JSON.stringify(proof,null,2));console.log(JSON.stringify(proof));
}finally{await browser.close();}
